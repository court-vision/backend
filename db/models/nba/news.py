"""
nba.news_items and its link tables (migration 0034).

One row per item from any news source, linked to the players and teams it is
about. data-platform's news pipeline writes it; the backend reads it for
`/v1/players/{id}/news`, `/v1/news`, Scout and the agent's news tools. The
`search` tsvector column is generated by Postgres and deliberately not a field
here, so no insert ever names it.

Mirrored byte-for-byte between backend and data-platform
(scripts/check_backend_mirror.py).
"""

from datetime import datetime, timezone

from peewee import BigAutoField, CharField, CompositeKey, DateTimeField, ForeignKeyField, TextField
from playhouse.postgres_ext import BinaryJSONField

from db.base import BaseModel
from db.models.nba.players import Player
from db.models.nba.teams import NBATeam

NEWS_KINDS = ("injury", "availability", "lineup", "transaction", "performance", "rumor", "other")
LINKED_BY = ("espn_id", "name")


def _now() -> datetime:
    return datetime.now(timezone.utc)


class NewsItem(BaseModel):
    id = BigAutoField()
    source = CharField(max_length=24)              # espn_injuries | espn_player_news | rotowire_rss | ...
    source_item_id = CharField(max_length=200)     # the source's id, or a hash of url + headline
    published_at = DateTimeField(null=True)        # the source's timestamp
    fetched_at = DateTimeField(default=_now)
    headline = TextField()
    body = TextField(null=True)                    # the blurb / one paragraph, never a full article
    url = TextField(null=True)
    attribution = TextField(null=True)
    kind = CharField(max_length=16, default="other")
    content_hash = CharField(max_length=64, null=True)   # normalized headline, cross-source dedup
    raw = BinaryJSONField(null=True)               # pruned after 30 days

    class Meta:
        table_name = "news_items"
        schema = "nba"
        indexes = ((("source", "source_item_id"), True),)


class NewsItemPlayer(BaseModel):
    news_item = ForeignKeyField(NewsItem, on_delete="CASCADE", backref="player_links", column_name="news_item_id")
    player = ForeignKeyField(Player, on_delete="CASCADE", backref="news_links", column_name="player_id")
    linked_by = CharField(max_length=8)            # espn_id | name

    class Meta:
        table_name = "news_item_players"
        schema = "nba"
        primary_key = CompositeKey("news_item", "player")


class NewsItemTeam(BaseModel):
    news_item = ForeignKeyField(NewsItem, on_delete="CASCADE", backref="team_links", column_name="news_item_id")
    team = ForeignKeyField(NBATeam, on_delete="CASCADE", backref="news_links", column_name="team_id")

    class Meta:
        table_name = "news_item_teams"
        schema = "nba"
        primary_key = CompositeKey("news_item", "team")
