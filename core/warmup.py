"""
Startup warm-up for the request path.

The first requests after every deploy (several a day) used to pay three cold
costs between them, in the first Week open's 9-11 parallel requests
(docs/PERF_AUDIT_2026-10.md, A2 and A3):

- Clerk's JWKS: each request fetched it itself, about 330 ms each in prod.
- An empty DB pool: Peewee opens connections one at a time, so the burst's
  requests queued behind each other's connects.
- The OpenAPI schema: generated by the first /openapi.json, 692 ms on the
  event loop, which stalled every other request in flight for as long.

`warm_request_path` pays them once in the lifespan, before the server accepts
traffic. Each part is best effort: a failure is logged, startup carries on,
and the request that needs the thing builds it the way it always has.
"""

import asyncio
import time

from fastapi import FastAPI

from core.clerk_auth import warm_clerk_jwks
from core.logging import get_logger
from core.settings import settings
from db.base import warm_db_pool

log = get_logger("warmup")

# How long startup waits for the JWKS. The fetch keeps going in its thread
# after that (its own timeout is 10 s) and still fills the cache, and requests
# that need the keys meanwhile wait for that one fetch rather than making
# their own.
JWKS_WAIT_S = 3.0


def warm_openapi(app: FastAPI) -> None:
    """Build and cache the OpenAPI schema (FastAPI keeps it on the app)."""
    started = time.perf_counter()
    try:
        app.openapi()
    except Exception as exc:
        # /openapi.json would fail the same way; that is no reason not to serve.
        log.exception("openapi_warm_failed", error=type(exc).__name__)
        return
    log.info("openapi_warmed", ms=round((time.perf_counter() - started) * 1000))


async def warm_request_path(app: FastAPI) -> None:
    """Fetch the JWKS, open pooled DB connections and build the OpenAPI schema.

    The JWKS fetch is a network wait in a worker thread, so it runs alongside
    the other two. Those two run one after the other: the schema build holds
    the GIL, and connects made under it measured ~70 ms each instead of ~3 ms
    locally, which would also make the logged connect time meaningless.
    """
    loop = asyncio.get_running_loop()
    jwks = loop.run_in_executor(None, warm_clerk_jwks)

    try:
        await warm_db_pool(settings.db_pool_warm_connections)
    except Exception as exc:  # warm_db_pool logs its own failures; this is the backstop
        log.warning("db_pool_warm_failed", error=type(exc).__name__)

    warm_openapi(app)

    try:
        await asyncio.wait_for(asyncio.shield(jwks), JWKS_WAIT_S)
    except asyncio.TimeoutError:
        log.warning("clerk_jwks_warm_slow", waited_s=JWKS_WAIT_S)
    except Exception as exc:  # warm_clerk_jwks logs its own failures; this is the backstop
        log.warning("clerk_jwks_warm_failed", error=type(exc).__name__)
