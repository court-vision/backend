-- Migration 0043: Dime's steering (the Dime autopilot plan, step 4).
--
-- Dime manages through the automations, not around them: its judgment enters
-- the planners as inputs. A hold is one such input on one player, for a run of
-- days that always ends:
--
--   keep      a roster player Dime won't drop: a stream lane holding his spot
--             keeps him through ends_on, and Dime's own proposals won't drop him
--   block     a player Dime won't add: no lane takes him, and Dime's own
--             proposals won't add him
--   override  his value on those days, as a share of his usual one (0 = Dime
--             expects him to miss, 0.5 = limited minutes): the lanes plan with
--             it, and at share 0 auto-lineup's fill treats him as out
--   pin       auto-lineup's fill leaves him where he is on those days. A lineup
--             chip that benches a player pins him for its day when it is sent,
--             so the fill doesn't start him again
--
-- Every hold carries its reason and shows in the Week desk, where the user can
-- clear it. None outlives ends_on: the readers only see holds whose ends_on is
-- today or later (the fantasy day, 3 AM ET), so nothing sweeps them. A hold is
-- made from a chip (`proposal_id`): Dime proposes it with `steer`, the user
-- applies it from the AI desk (`applied_by` user); `dime` is for when Dime may
-- apply its own, which the acting step decides. Holds steer the automations and
-- Dime's own proposals only: the user's own moves are never refused for one.
--
-- usr.ai_proposals gains three kinds, with what they do in `action`:
--   steer          holds to set and holds to clear (POST /teams/{id}/holds)
--   lane           start, pause, resume or stop a stream lane (the lane routes)
--   cancel_pickup  cancel a pending scheduled pickup (the pickup route)
-- Each is applied through the Week desk's own route with `proposal_id`, which
-- marks the chip sent; in a check-in it is a shadow proposal like any other.

CREATE TABLE IF NOT EXISTS usr.team_holds (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id        integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    user_id        integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    kind           text         NOT NULL,
    player_id      integer      NOT NULL,              -- ESPN, as the boards and the pool key players
    nba_player_id  integer,
    player_name    text         NOT NULL,
    player_team    text,
    share          numeric(3, 2),                      -- override only
    starts_on      date         NOT NULL,
    ends_on        date         NOT NULL,
    reason         text         NOT NULL,
    proposal_id    bigint       REFERENCES usr.ai_proposals (id) ON DELETE SET NULL,
    applied_by     text         NOT NULL DEFAULT 'user',
    created_at     timestamp with time zone NOT NULL DEFAULT now(),
    cleared_at     timestamp with time zone,
    cleared_by     text,
    CONSTRAINT team_holds_kind_check CHECK (kind IN ('keep', 'block', 'override', 'pin')),
    CONSTRAINT team_holds_share_check
        CHECK ((kind = 'override' AND share IS NOT NULL AND share >= 0 AND share <= 2)
               OR (kind <> 'override' AND share IS NULL)),
    CONSTRAINT team_holds_days_check CHECK (ends_on >= starts_on AND ends_on <= starts_on + 28),
    CONSTRAINT team_holds_reason_check CHECK (char_length(reason) BETWEEN 1 AND 200),
    CONSTRAINT team_holds_applied_by_check CHECK (applied_by IN ('user', 'dime')),
    CONSTRAINT team_holds_cleared_check
        CHECK ((cleared_at IS NULL AND cleared_by IS NULL)
               OR (cleared_at IS NOT NULL AND cleared_by IS NOT NULL AND cleared_by IN ('user', 'dime')))
);

CREATE INDEX IF NOT EXISTS team_holds_live
    ON usr.team_holds (team_id, ends_on)
    WHERE cleared_at IS NULL;

COMMENT ON TABLE usr.team_holds IS
    'Dime''s steering inputs into the automations (keep, block, override, pin), one player and a run of days '
    'each, with a reason; read only through ends_on. Made from a chip the user applied; cleared from the Week desk.';

ALTER TABLE usr.ai_proposals ADD COLUMN IF NOT EXISTS action jsonb;

ALTER TABLE usr.ai_proposals DROP CONSTRAINT IF EXISTS ai_proposals_kind_check;
ALTER TABLE usr.ai_proposals ADD CONSTRAINT ai_proposals_kind_check
    CHECK (kind IN ('transaction', 'scheduled', 'lineup', 'steer', 'lane', 'cancel_pickup'));

ALTER TABLE usr.ai_proposals DROP CONSTRAINT IF EXISTS ai_proposals_move_check;
ALTER TABLE usr.ai_proposals ADD CONSTRAINT ai_proposals_move_check
    CHECK ((kind = 'lineup' AND moves IS NOT NULL)
           OR (kind IN ('steer', 'lane', 'cancel_pickup') AND action IS NOT NULL)
           OR (kind IN ('transaction', 'scheduled') AND (add_player_id IS NOT NULL OR drop_player_id IS NOT NULL)));

COMMENT ON COLUMN usr.ai_proposals.action IS
  'Steering chips only (steer, lane, cancel_pickup): what applying the chip does, as its route reads it.';
