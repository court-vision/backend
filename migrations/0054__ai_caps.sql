-- Migration 0054: AI spend caps you can change without a deploy.
--
-- usr.ai_spend has three lines, each with a monthly budget read from the
-- environment: the AI desk (AI_MONTHLY_BUDGET_USD, shared by every allowed user,
-- each of whom may spend an equal part of it), Dime's check-ins
-- (AUTOPILOT_MONTHLY_BUDGET_USD) and the live rankings' analyst
-- (ANALYST_MONTHLY_BUDGET_USD). A row here replaces one of those numbers:
--
--   user_id NULL   the line's monthly cap, for everyone on it
--   user_id set    one user's monthly cap on that line (desk or autopilot; the
--                  analyst's reads belong to no user)
--
-- With no row, the environment's number applies, and a user's desk cap is the
-- desk's cap divided by the allowed users, as before. A user has no cap of
-- their own on the autopilot line unless a row sets one. Deleting a row hands
-- the number back to the environment. Each reservation reads the caps as it
-- starts, so a change applies from the next turn, check-in or read on.
--
-- Rows are written from the data platform's dashboard (the AI spend page),
-- through the backend: `updated_by` is the name typed there.

CREATE TABLE IF NOT EXISTS usr.ai_caps (
    id           bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line         text     NOT NULL,
    user_id      integer  REFERENCES usr.users (user_id) ON DELETE CASCADE,
    monthly_usd  numeric(10, 2) NOT NULL,
    updated_at   timestamp with time zone NOT NULL DEFAULT now(),
    updated_by   text,
    CONSTRAINT ai_caps_line_check CHECK (line IN ('desk', 'autopilot', 'analyst')),
    CONSTRAINT ai_caps_user_check CHECK (user_id IS NULL OR line <> 'analyst'),
    CONSTRAINT ai_caps_amount_check CHECK (monthly_usd >= 0)
);

-- One cap per line, and one per user on a line
CREATE UNIQUE INDEX IF NOT EXISTS ai_caps_line_uniq ON usr.ai_caps (line) WHERE user_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ai_caps_line_user_uniq ON usr.ai_caps (line, user_id) WHERE user_id IS NOT NULL;

COMMENT ON TABLE usr.ai_caps IS
  'Monthly AI spend caps set from the dashboard: a line''s (user_id NULL) or one user''s on a line. No row: the environment''s number applies.';
