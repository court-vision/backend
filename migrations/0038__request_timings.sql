-- Migration 0038: one row per API request, with where its time went.
--
-- ops is a new schema for the services' own operational data. The backend
-- writes ops.request_timings in batches (services/request_timings.py) and
-- deletes rows past REQUEST_TIMINGS_RETENTION_DAYS (30); data-platform's
-- Latency page reads it.
--
-- `parts` splits duration_ms into buckets and sums to it: {"espn": 212.4,
-- "postgres": 18.0, "wait": 3.1, "app": 40.2}. `calls` counts each bucket's
-- calls: {"espn": 2, "postgres": 7}. Both are maps rather than a column per
-- bucket so a new bucket needs no migration. `trace_id` is set only when the
-- request's trace went to Railway, so the page can link to it.

CREATE SCHEMA IF NOT EXISTS ops;

CREATE TABLE IF NOT EXISTS ops.request_timings (
    id           bigint           GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at   timestamp with time zone NOT NULL,
    service      text             NOT NULL,
    method       text             NOT NULL,
    route        text             NOT NULL,
    status_code  smallint         NOT NULL,
    duration_ms  double precision NOT NULL,
    parts        jsonb            NOT NULL DEFAULT '{}'::jsonb,
    calls        jsonb            NOT NULL DEFAULT '{}'::jsonb,
    trace_id     varchar(32),
    version      text
);

CREATE INDEX IF NOT EXISTS request_timings_started_at_idx
    ON ops.request_timings (started_at);
CREATE INDEX IF NOT EXISTS request_timings_route_started_at_idx
    ON ops.request_timings (route, started_at);
