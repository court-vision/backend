-- Migration 0042: Dime's check-ins, in shadow (the Dime autopilot plan, step 3).
--
-- A check-in is a turn Dime starts itself on a schedule: the morning of a game
-- day (the weekly one on a matchup's first day), shortly before the first tip,
-- and a follow-up the next morning on the night's games. The server writes the
-- opening message, Dime works with its tools, and the conversation lands in the
-- AI desk's check-ins. In shadow nothing is sent: Dime reads what the
-- automations (auto-lineup, stream lanes, scheduled pickups) are about to do and
-- logs what it would keep or change.
--
-- usr.autopilot is one row per team Dime runs on. A team needs both this row
-- and an entry in AUTOPILOT_TEAM_IDS; either alone does nothing. `paused_at`
-- is the Pause switch (no deploy needed); `active_since` is when it last
-- started or resumed, so a check-in that fell due before then is never
-- counted as missed. How Dime may act on a team (one setting, or one per
-- capability) is decided with step 5 and lands as its own migration; this row
-- holds no autonomy yet.
--
-- usr.ai_checkins is one row per check-in: claimed by its insert (one per team,
-- kind and day, so ticks on two replicas can't both run it; a manual "run now"
-- is outside that rule), then settled with its turn's outcome and cost.
-- `missed` is a check-in whose window closed before it could run; `skipped`
-- one that was refused (the check-ins' monthly budget, the day's cap).
--
-- usr.ai_decisions is what a check-in decided, one row per call, holds
-- included: which part of the team it is about (`area`), whose plan it
-- reviewed (`automation`), keep it or change it (`call`), the one-line summary
-- and reason, and the proposal behind a change (a shadow proposal: checked by
-- the server like a chip, never sendable). `verdict` is the user's agree /
-- disagree, the measure for "you agree with most of what it would have done".
--
-- Also: a conversation has a `kind` (chat, or the conversation a check-in
-- started); a proposal can be `shadow` (made in a check-in: logged, never
-- staged or sent); and usr.ai_spend has a `line` (desk, or autopilot), so the
-- check-ins have their own monthly budget and can't eat the AI desk's.

CREATE TABLE IF NOT EXISTS usr.autopilot (
    team_id        integer      PRIMARY KEY REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    user_id        integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    created_at     timestamp with time zone NOT NULL DEFAULT now(),
    updated_at     timestamp with time zone NOT NULL DEFAULT now(),
    active_since   timestamp with time zone NOT NULL DEFAULT now(),
    paused_at      timestamp with time zone,
    paused_by      text,
    paused_reason  text,
    CONSTRAINT autopilot_paused_check
        CHECK ((paused_at IS NULL AND paused_by IS NULL)
               OR (paused_at IS NOT NULL AND paused_by IN ('user', 'system')))
);

COMMENT ON TABLE usr.autopilot IS
    'Teams Dime runs check-ins on (with AUTOPILOT_TEAM_IDS). paused_at is the Pause switch. '
    'How Dime may act is added with the acting step; this row holds no autonomy yet.';

ALTER TABLE usr.ai_conversations ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'chat';
ALTER TABLE usr.ai_conversations DROP CONSTRAINT IF EXISTS ai_conversations_kind_check;
ALTER TABLE usr.ai_conversations ADD CONSTRAINT ai_conversations_kind_check
    CHECK (kind IN ('chat', 'checkin'));

CREATE TABLE IF NOT EXISTS usr.ai_checkins (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id          integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    user_id          integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    kind             text         NOT NULL,
    nba_date         date         NOT NULL,              -- the game day it is about
    manual           boolean      NOT NULL DEFAULT false, -- run now, from the AI desk
    due_at           timestamp with time zone NOT NULL,
    state            text         NOT NULL DEFAULT 'running',
    reason           text,                               -- why it failed, was missed or skipped
    conversation_id  bigint       REFERENCES usr.ai_conversations (id) ON DELETE SET NULL,
    turn_id          bigint       REFERENCES usr.ai_turns (id) ON DELETE SET NULL,
    cost_micros      bigint       NOT NULL DEFAULT 0,
    started_at       timestamp with time zone NOT NULL DEFAULT now(),
    finished_at      timestamp with time zone,
    CONSTRAINT ai_checkins_kind_check CHECK (kind IN ('morning', 'weekly', 'pre_lock', 'night')),
    CONSTRAINT ai_checkins_state_check CHECK (state IN ('running', 'done', 'failed', 'missed', 'skipped'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ai_checkins_slot_uq
    ON usr.ai_checkins (team_id, kind, nba_date)
    WHERE NOT manual;

CREATE INDEX IF NOT EXISTS ai_checkins_team
    ON usr.ai_checkins (team_id, started_at DESC);

COMMENT ON TABLE usr.ai_checkins IS
    'Turns Dime started itself (morning, weekly, pre_lock, night), one per team, kind and day; '
    'settled with the turn''s outcome and cost.';

CREATE TABLE IF NOT EXISTS usr.ai_decisions (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkin_id   bigint       NOT NULL REFERENCES usr.ai_checkins (id) ON DELETE CASCADE,
    user_id      integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    team_id      integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    area         text         NOT NULL,
    automation   text         NOT NULL DEFAULT 'none',
    call         text         NOT NULL,
    summary      text         NOT NULL,
    reason       text         NOT NULL,
    proposal_id  bigint       REFERENCES usr.ai_proposals (id) ON DELETE SET NULL,
    verdict      text,
    verdict_at   timestamp with time zone,
    created_at   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ai_decisions_area_check CHECK (area IN ('lineup', 'streaming', 'adds_drops', 'other')),
    CONSTRAINT ai_decisions_automation_check
        CHECK (automation IN ('auto_lineup', 'stream_lane', 'scheduled_pickup', 'none')),
    CONSTRAINT ai_decisions_call_check CHECK (call IN ('hold', 'change')),
    CONSTRAINT ai_decisions_summary_check CHECK (char_length(summary) BETWEEN 1 AND 200),
    CONSTRAINT ai_decisions_reason_check CHECK (char_length(reason) BETWEEN 1 AND 400),
    CONSTRAINT ai_decisions_verdict_check
        CHECK ((verdict IS NULL AND verdict_at IS NULL)
               OR (verdict IN ('agree', 'disagree') AND verdict_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS ai_decisions_checkin ON usr.ai_decisions (checkin_id, id);
CREATE INDEX IF NOT EXISTS ai_decisions_team ON usr.ai_decisions (team_id, created_at DESC);

COMMENT ON TABLE usr.ai_decisions IS
    'What a check-in decided, holds included: area, the automation whose plan it reviewed, hold or change, '
    'the reason, the shadow proposal behind a change, and the user''s agree / disagree.';

ALTER TABLE usr.ai_proposals DROP CONSTRAINT IF EXISTS ai_proposals_state_check;
ALTER TABLE usr.ai_proposals ADD CONSTRAINT ai_proposals_state_check
    CHECK (state IN ('proposed', 'sent', 'dismissed', 'shadow'));

ALTER TABLE usr.ai_spend ADD COLUMN IF NOT EXISTS line text NOT NULL DEFAULT 'desk';
ALTER TABLE usr.ai_spend DROP CONSTRAINT IF EXISTS ai_spend_line_check;
ALTER TABLE usr.ai_spend ADD CONSTRAINT ai_spend_line_check CHECK (line IN ('desk', 'autopilot'));

CREATE INDEX IF NOT EXISTS ai_spend_line_created ON usr.ai_spend (line, created_at);
