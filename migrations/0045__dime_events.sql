-- Migration 0045: Dime's event check-ins (the Dime autopilot plan, step 6).
--
-- Until now Dime's check-ins ran on a clock: the morning, before the first tip,
-- and the next morning (step 3). Here news starts them too. When the
-- availability pipeline resolves a new verdict for a player whose game has not
-- tipped (out, doubtful, or available again), or the news feed stores an item
-- about a player's health, role or roster spot, data-platform tells the
-- backend, and each team Dime runs that rosters the player gets an event: a
-- check-in about it, before his game locks.
--
-- usr.autopilot_events is one row per (team, thing that happened): the
-- verdict's change (player, game date and the time it changed, so the same
-- change posted twice is one row, and a later flip back is a new one) or the
-- news item. `summary` is the server's one line about it, written when it
-- arrives, so the brief and the AI desk read the same words. An event is
-- `pending` until a check-in takes it (`checkin_id`): an event check-in started
-- for it, or a scheduled one that was about to run anyway and lists it in its
-- brief. One that can't be answered any more (his game tipped, or the news is
-- half a day old) is `dropped` with the reason.
--
-- news_item_id carries no foreign key, like 0035's game_id: rolling 0035 back
-- drops nba.news_items, and this table must not stand in its way. The summary
-- keeps what the event said.
--
-- usr.ai_checkins gains the kind `event`. Event check-ins are not slots (a team
-- can have several in a day, each claimed for its events), so the one-per-slot
-- index leaves them out; the one-running-per-team index still holds them.

CREATE TABLE IF NOT EXISTS usr.autopilot_events (
    id                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id           integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    user_id           integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    source            text         NOT NULL,
    player_id         integer      NOT NULL REFERENCES nba.players (id) ON DELETE CASCADE,
    nba_date          date         NOT NULL,              -- the fantasy day it came in on
    game_date         date,                               -- availability: the verdict's game date
    game_id           varchar(20),
    tip_at            timestamp with time zone,           -- his game's tip, when he has one that day
    verdict           text,                               -- availability: the new verdict
    previous_verdict  text,
    changed_at        timestamp with time zone,           -- availability: when the verdict changed
    news_item_id      bigint,                             -- news: nba.news_items.id (no FK, see above)
    news_kind         text,
    summary           text         NOT NULL,
    received_at       timestamp with time zone NOT NULL DEFAULT now(),
    state             text         NOT NULL DEFAULT 'pending',
    reason            text,                               -- why it was dropped
    checkin_id        bigint       REFERENCES usr.ai_checkins (id) ON DELETE SET NULL,
    taken_at          timestamp with time zone,
    CONSTRAINT autopilot_events_source_check CHECK (source IN ('availability', 'news')),
    CONSTRAINT autopilot_events_state_check CHECK (state IN ('pending', 'taken', 'dropped')),
    CONSTRAINT autopilot_events_shape_check CHECK (
        (source = 'availability' AND verdict IS NOT NULL AND game_date IS NOT NULL AND changed_at IS NOT NULL)
        OR (source = 'news' AND news_item_id IS NOT NULL)),
    CONSTRAINT autopilot_events_summary_check CHECK (char_length(summary) BETWEEN 1 AND 400)
);

-- The same change, posted by two ticks (or retried), is one event per team
CREATE UNIQUE INDEX IF NOT EXISTS autopilot_events_verdict_once_uq
    ON usr.autopilot_events (team_id, player_id, game_date, changed_at)
    WHERE source = 'availability';
CREATE UNIQUE INDEX IF NOT EXISTS autopilot_events_news_once_uq
    ON usr.autopilot_events (team_id, news_item_id, player_id)
    WHERE source = 'news';

CREATE INDEX IF NOT EXISTS autopilot_events_pending
    ON usr.autopilot_events (team_id, received_at)
    WHERE state = 'pending';
CREATE INDEX IF NOT EXISTS autopilot_events_checkin
    ON usr.autopilot_events (checkin_id);

COMMENT ON TABLE usr.autopilot_events IS
    'What came in about a rostered player (a verdict change, a news item) on a team Dime runs; pending '
    'until a check-in takes it, or dropped with the reason.';

ALTER TABLE usr.ai_checkins DROP CONSTRAINT IF EXISTS ai_checkins_kind_check;
ALTER TABLE usr.ai_checkins ADD CONSTRAINT ai_checkins_kind_check
    CHECK (kind IN ('morning', 'weekly', 'pre_lock', 'night', 'event'));

DROP INDEX IF EXISTS usr.ai_checkins_slot_uq;
CREATE UNIQUE INDEX IF NOT EXISTS ai_checkins_slot_uq
    ON usr.ai_checkins (team_id, kind, nba_date)
    WHERE NOT manual AND kind <> 'event';
