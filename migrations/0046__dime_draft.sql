-- Migration 0046: Dime in the Draft desk (the Dime autopilot plan, step 7).
--
-- The Draft desk already does a good drafter's arithmetic (the board, its
-- recommendations, mocks, the recap). Here Dime sits beside it: a plan before
-- the draft (set as the room's punts), a short note when the user's pick is
-- near, a read of the recap afterwards, and, in a mock room, the user's seat:
-- Dime makes the user's picks itself, through the room's own pick path.
--
-- usr.ai_draft_rooms is Dime's state in one room, one row per room it has
-- touched: `notes` (a note when each of the user's picks is near) and `seat`
-- (off; drafting while Dime holds the user's seat in a mock; stopping when the
-- user has asked it to hand the seat back after the pick it is making).
-- `seat_reason` says why the seat last stopped (the draft ended, the user
-- stopped it, a pick failed).
--
-- usr.ai_draft_notes is one row per note Dime writes in a room: `plan`,
-- `pick` (about the user's pick `for_pick`; `seat` when Dime made that pick
-- itself) or `recap`. Each note is one agent turn in a conversation of its own
-- (kind `draft`); the row is claimed by its insert and settled with the turn's
-- answer and cost. `facts` holds the numbers the server read off the board for
-- the note (the top recommendations, who is likely gone before the user's
-- pick), shown beside Dime's words, so every number on it comes from the
-- board. A plan note keeps the punts it set and the ones it replaced; a seat
-- note keeps the pick it recorded. One note runs per room at a time, and one
-- pick note per pick (failed ones aside, so a retry can land).
--
-- Also: a conversation can be `draft`, and a pick can be `dime` (made by Dime
-- in a mock seat; only the server may say so, like `mock`).

ALTER TABLE usr.ai_conversations DROP CONSTRAINT IF EXISTS ai_conversations_kind_check;
ALTER TABLE usr.ai_conversations ADD CONSTRAINT ai_conversations_kind_check
    CHECK (kind IN ('chat', 'checkin', 'draft'));

ALTER TABLE usr.draft_picks DROP CONSTRAINT IF EXISTS draft_picks_source_check;
ALTER TABLE usr.draft_picks ADD CONSTRAINT draft_picks_source_check
    CHECK (source IN ('manual', 'espn_sync', 'import', 'keeper', 'mock', 'dime'));

CREATE TABLE IF NOT EXISTS usr.ai_draft_rooms (
    session_id   integer      PRIMARY KEY REFERENCES usr.draft_sessions (id) ON DELETE CASCADE,
    user_id      integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    notes        boolean      NOT NULL DEFAULT false,
    seat         text         NOT NULL DEFAULT 'off',
    seat_reason  text,
    created_at   timestamp with time zone NOT NULL DEFAULT now(),
    updated_at   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ai_draft_rooms_seat_check CHECK (seat IN ('off', 'drafting', 'stopping'))
);

COMMENT ON TABLE usr.ai_draft_rooms IS
    'Dime in one draft room: a note at each of the user''s picks (notes), and whether Dime holds the '
    'user''s seat in a mock (seat).';

CREATE TABLE IF NOT EXISTS usr.ai_draft_notes (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id       integer      NOT NULL REFERENCES usr.draft_sessions (id) ON DELETE CASCADE,
    user_id          integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    kind             text         NOT NULL,
    for_pick         integer,
    seat             boolean      NOT NULL DEFAULT false,
    state            text         NOT NULL DEFAULT 'running',
    reason           text,
    facts            jsonb        NOT NULL DEFAULT '{}'::jsonb,
    text             text,
    plan             text,
    punts            jsonb,
    punts_before     jsonb,
    took             jsonb,
    conversation_id  bigint       REFERENCES usr.ai_conversations (id) ON DELETE SET NULL,
    turn_id          bigint       REFERENCES usr.ai_turns (id) ON DELETE SET NULL,
    cost_micros      bigint       NOT NULL DEFAULT 0,
    created_at       timestamp with time zone NOT NULL DEFAULT now(),
    finished_at      timestamp with time zone,
    CONSTRAINT ai_draft_notes_kind_check CHECK (kind IN ('plan', 'pick', 'recap')),
    CONSTRAINT ai_draft_notes_state_check CHECK (state IN ('running', 'done', 'failed')),
    CONSTRAINT ai_draft_notes_pick_check CHECK ((kind = 'pick') = (for_pick IS NOT NULL)),
    CONSTRAINT ai_draft_notes_seat_check CHECK (NOT seat OR kind = 'pick')
);

-- One note at a time in a room: two clicks (or the seat and a pick note) can't both start a turn
CREATE UNIQUE INDEX IF NOT EXISTS ai_draft_notes_one_running_uq
    ON usr.ai_draft_notes (session_id)
    WHERE state = 'running';

-- One note per pick, and one pick Dime makes per pick; a failed one leaves room for a retry
CREATE UNIQUE INDEX IF NOT EXISTS ai_draft_notes_pick_uq
    ON usr.ai_draft_notes (session_id, for_pick, seat)
    WHERE kind = 'pick' AND state <> 'failed';

CREATE INDEX IF NOT EXISTS ai_draft_notes_session
    ON usr.ai_draft_notes (session_id, id DESC);

COMMENT ON TABLE usr.ai_draft_notes IS
    'Dime''s notes in a draft room (plan, pick, recap), each one agent turn: the board''s numbers it read '
    '(facts), its words, and the punts it set or the pick it made.';
