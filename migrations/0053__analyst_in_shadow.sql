-- The analyst in shadow (the Live rankings plan, step 4).
--
-- Each morning an AI analyst reads the stored news and availability reports
-- for a short list of players and writes down what a box score cannot say:
-- how long he is out, whether a role change is temporary, whether he is
-- limited when he returns. It writes the same kind of note you write by hand
-- in the projections editor (migration 0052): inputs with an end, a source
-- and a day to read it again, never a rank.
--
-- scope 'analyst' on nba.projection_adjustments
--   The analyst's notes sit in a scope of their own, one live note per player
--   per season, beside the 'season' note written by hand and the 'preseason'
--   adjustment. Three things follow from that:
--     * in shadow the live projection does not read them (it reads 'season'
--       alone), so nothing the analyst writes can reach a board anyone sees;
--     * a note written by hand is never overwritten: the two are different
--       rows, and wherever both are read the one written by hand wins;
--     * the analyst's history is append-only like every other row here.
--   A second projection (nba.player_projections source 'cv_live_shadow') and
--   two second boards (nba.daily_rankings source 'cv_shadow') are built each
--   morning with them applied. Neither column has a list of allowed sources.
--
-- nba.analyst_reads
--   One row per player the analyst was asked about on a morning: why the
--   screen picked him, what the read came to, the note it left (if any), what
--   it would say against a note written by hand, and what the read cost. This
--   is the morning digest, the audit of a refused note, and the measure of
--   what the shadow run spends.
--
--     outcome  note       a new or changed note was stored
--              unchanged  the note it already had still says it
--              none       nothing a box score cannot say, or nothing to cite
--              retired    the note it had no longer holds, and was withdrawn
--              refused    the server refused what came back (no cited item,
--                         outside its bounds); `summary` says why
--              declined   the model declined the request
--              failed     the read did not complete; the next run reads again
--
--   `fingerprint` is a hash of what the read was shown. A player whose facts
--   have not changed since his last completed read is not read again.
--
-- usr.ai_spend line 'analyst'
--   The reads are priced like every other model call and reserved against a
--   monthly budget of their own (ANALYST_MONTHLY_BUDGET_USD), so a morning of
--   reads cannot use up the AI desk's budget or the check-ins'. They belong to
--   no user, so user_id may be null on that line and on no other.

ALTER TABLE nba.projection_adjustments
    DROP CONSTRAINT IF EXISTS projection_adjustments_scope_check,
    DROP CONSTRAINT IF EXISTS projection_adjustments_season_note_check;

ALTER TABLE nba.projection_adjustments
    ADD CONSTRAINT projection_adjustments_scope_check CHECK (scope IN ('preseason', 'season', 'analyst')),
    -- A note in season, whoever wrote it, always has a day it is read again and
    -- sets no per-stat multiplier. A preseason adjustment has none of the
    -- in-season fields.
    ADD CONSTRAINT projection_adjustments_season_note_check CHECK (
        (scope IN ('season', 'analyst') AND review_date IS NOT NULL AND rates IS NULL)
        OR (scope = 'preseason' AND until_date IS NULL AND depends_on_player_id IS NULL
            AND return_earliest IS NULL AND return_latest IS NULL AND review_date IS NULL)
    );

CREATE TABLE IF NOT EXISTS nba.analyst_reads (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season           varchar(7)   NOT NULL,
    as_of_date       date         NOT NULL,       -- the morning the read was for
    player_id        integer      NOT NULL REFERENCES nba.players (id) ON DELETE CASCADE,
    reasons          jsonb        NOT NULL,       -- why the screen picked him: [{"rule", "detail"}]
    fingerprint      varchar(64)  NOT NULL,       -- a hash of what the read was shown
    outcome          varchar(12)  NOT NULL
        CHECK (outcome IN ('note', 'unchanged', 'none', 'retired', 'refused', 'declined', 'failed')),
    summary          text,                        -- the analyst's reason, or why the read was refused or failed
    note_id          integer      REFERENCES nba.projection_adjustments (id) ON DELETE SET NULL,
    disagrees        text,                        -- what it would say against the note written by hand; null when none or it agrees
    proposal         jsonb,                       -- what came back, as it came back (kept when refused)
    model            varchar(64),
    prompt_version   varchar(16),
    input_tokens     integer      NOT NULL DEFAULT 0,
    output_tokens    integer      NOT NULL DEFAULT 0,
    cost_micros      bigint       NOT NULL DEFAULT 0,
    created_at       timestamp with time zone NOT NULL DEFAULT now(),
    pipeline_run_id  uuid
);

-- The morning digest reads a day; "has this been read before" reads a player's newest
CREATE INDEX IF NOT EXISTS analyst_reads_day_idx
    ON nba.analyst_reads (season, as_of_date);
CREATE INDEX IF NOT EXISTS analyst_reads_player_idx
    ON nba.analyst_reads (player_id, created_at DESC);

COMMENT ON TABLE nba.analyst_reads IS
    'One row per player the AI analyst read on a morning (Live rankings step 4): why, the outcome, the note, the cost.';

ALTER TABLE usr.ai_spend ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE usr.ai_spend
    DROP CONSTRAINT IF EXISTS ai_spend_line_check,
    DROP CONSTRAINT IF EXISTS ai_spend_user_check;
ALTER TABLE usr.ai_spend
    ADD CONSTRAINT ai_spend_line_check CHECK (line IN ('desk', 'autopilot', 'analyst')),
    ADD CONSTRAINT ai_spend_user_check CHECK (user_id IS NOT NULL OR line = 'analyst');
