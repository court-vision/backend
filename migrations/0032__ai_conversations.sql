-- Migration 0032: the AI agent's conversations (docs/AI_AGENT_PLAN.md § 1).
--
-- usr.ai_conversations is one chat in the AI desk, optionally pinned to one of
-- the user's teams. `busy_until` is the claim a turn holds while it runs: two
-- turns on one conversation at once would interleave its history, so a second
-- one is refused until the first ends or its claim lapses.
--
-- usr.ai_turns is one user message and everything the agent did with it.
-- `messages` holds the Messages API messages the turn appended, exactly as
-- sent and received (thinking blocks included): the next turn replays every
-- successful turn's messages in order, unedited, because Claude Opus 5.5
-- refuses a replayed thinking block whose earlier history changed. A turn that
-- failed keeps its row (the cost is real) but no `messages`, so it is never
-- replayed. `results` are the tool results by id ("r3"), which display blocks
-- point at; `parts` is the answer as the user saw it, text and blocks in order.
-- `cost_micros` (millionths of a dollar) is the turn's own cost, for display.
--
-- usr.ai_spend is what the monthly caps sum, kept apart from the conversations
-- so deleting one can't hand its spend back. Each turn reserves its ceiling
-- here before it starts (under a lock, so turns started at once can't all pass
-- the same check) and settles the row to its real cost when it is written. A
-- reservation that is never settled stays charged at the ceiling.

CREATE TABLE IF NOT EXISTS usr.ai_conversations (
    id          bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    team_id     integer      REFERENCES usr.teams (team_id) ON DELETE SET NULL,
    title       text,
    created_at  timestamp with time zone NOT NULL DEFAULT now(),
    updated_at  timestamp with time zone NOT NULL DEFAULT now(),
    busy_until  timestamp with time zone
);

CREATE INDEX IF NOT EXISTS ai_conversations_user_updated_idx
    ON usr.ai_conversations (user_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS usr.ai_turns (
    id                          bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id             bigint   NOT NULL REFERENCES usr.ai_conversations (id) ON DELETE CASCADE,
    user_id                     integer  NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    created_at                  timestamp with time zone NOT NULL DEFAULT now(),
    message                     text     NOT NULL,
    messages                    jsonb,
    results                     jsonb    NOT NULL DEFAULT '{}'::jsonb,
    parts                       jsonb    NOT NULL DEFAULT '[]'::jsonb,
    tool_calls                  jsonb    NOT NULL DEFAULT '[]'::jsonb,
    outcome                     text     NOT NULL,
    model                       text,
    model_calls                 integer  NOT NULL DEFAULT 0,
    input_tokens                integer  NOT NULL DEFAULT 0,
    output_tokens               integer  NOT NULL DEFAULT 0,
    cache_read_input_tokens     integer  NOT NULL DEFAULT 0,
    cache_creation_input_tokens integer  NOT NULL DEFAULT 0,
    context_tokens              integer  NOT NULL DEFAULT 0,
    cost_micros                 bigint   NOT NULL DEFAULT 0,
    duration_ms                 integer,
    ungrounded_numbers          integer,
    feedback                    text,
    CONSTRAINT ai_turns_feedback_check CHECK (feedback IS NULL OR feedback IN ('up', 'down'))
);

CREATE INDEX IF NOT EXISTS ai_turns_conversation_idx
    ON usr.ai_turns (conversation_id, id);

CREATE TABLE IF NOT EXISTS usr.ai_spend (
    id           bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      integer  NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    turn_id      bigint   REFERENCES usr.ai_turns (id) ON DELETE SET NULL,
    created_at   timestamp with time zone NOT NULL DEFAULT now(),
    cost_micros  bigint   NOT NULL,
    settled      boolean  NOT NULL DEFAULT false
);

-- The monthly sums: one user's month, and everyone's
CREATE INDEX IF NOT EXISTS ai_spend_user_created_idx
    ON usr.ai_spend (user_id, created_at);
CREATE INDEX IF NOT EXISTS ai_spend_created_idx
    ON usr.ai_spend (created_at);

COMMENT ON TABLE usr.ai_conversations IS
  'AI desk conversations (docs/AI_AGENT_PLAN.md). busy_until is a running turn''s claim.';
COMMENT ON TABLE usr.ai_turns IS
  'One message to the AI agent and its answer. messages is replayed verbatim by later turns.';
COMMENT ON TABLE usr.ai_spend IS
  'The AI agent''s spend ledger: one reservation per turn, settled to its cost. The monthly caps sum it; deleting a conversation leaves it.';
