-- Migration 0055: what the user asks Dime to do at a time (the Dime desk redesign, step 2;
-- services/ai/asks.py).
--
-- In a chat the user can ask Dime to do something later ("at 6:30 tonight, check whether he
-- plays and swap him out if he doesn't"). Dime saves it here with its schedule_ask tool; the
-- user or Dime can cancel it while it waits. When it falls due it runs as a check-in of the new
-- kind `ask` (usr.ai_checkins), one Dime turn on the check-ins budget, and `checkin_id` points at
-- that run.
--
-- `state` is the ask's own part: pending (waiting for its time), started (its check-in ran;
-- how that went is the check-in's state), cancelled, missed (still waiting an hour past its
-- time), skipped (the budget or access refused it) or failed (its check-in couldn't start).

CREATE TABLE IF NOT EXISTS usr.ai_asks (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    team_id          integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    conversation_id  bigint       REFERENCES usr.ai_conversations (id) ON DELETE SET NULL,  -- where it was asked
    what             text         NOT NULL,
    due_at           timestamp with time zone NOT NULL,
    state            text         NOT NULL DEFAULT 'pending',
    reason           text,
    checkin_id       bigint       REFERENCES usr.ai_checkins (id) ON DELETE SET NULL,
    created_at       timestamp with time zone NOT NULL DEFAULT now(),
    updated_at       timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT ai_asks_state_check
        CHECK (state IN ('pending', 'started', 'cancelled', 'missed', 'skipped', 'failed')),
    CONSTRAINT ai_asks_what_check CHECK (length(what) BETWEEN 1 AND 500)
);

CREATE INDEX IF NOT EXISTS ai_asks_pending_due
    ON usr.ai_asks (due_at)
    WHERE state = 'pending';

CREATE INDEX IF NOT EXISTS ai_asks_team_due
    ON usr.ai_asks (team_id, due_at);

CREATE UNIQUE INDEX IF NOT EXISTS ai_asks_checkin_uq
    ON usr.ai_asks (checkin_id)
    WHERE checkin_id IS NOT NULL;

COMMENT ON TABLE usr.ai_asks IS
    'What a user asked Dime to do at a time; each runs once, as a check-in of kind ask.';

-- An ask runs as a check-in of its own kind. It is a manual one (the user asked for it), so the
-- one-per-slot index already leaves it out.
ALTER TABLE usr.ai_checkins DROP CONSTRAINT IF EXISTS ai_checkins_kind_check;
ALTER TABLE usr.ai_checkins ADD CONSTRAINT ai_checkins_kind_check
    CHECK (kind IN ('morning', 'weekly', 'pre_lock', 'night', 'event', 'ask'));
