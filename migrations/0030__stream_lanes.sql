-- Migration 0030: stream lanes.
--
-- usr.stream_lanes holds a standing order for one roster spot: keep it
-- streaming for the rest of the matchup (docs/STREAM_LANE_PLAN.md). It is not a
-- list of pickups. Before each day of the matchup, at the moment a pickup for
-- that day can first be made (a scheduled pickup's timing rule), the executor
-- job re-plans the spot from the board, the pool and the adds left
-- (services/stream_planner.py). When the plan's first step is a switch, it
-- inserts a scheduled pickup for that day carrying the lane's id, and the
-- pickup executor makes it like any other. `projection` is the plan as of the
-- last decision (or the start): what the desk shows, and what the next
-- decision is compared with when it says why it differs.
--
-- A team has at most one lane that is active or paused: one spot's plan can't
-- see another's, and they would draw on the same adds.
--
-- usr.stream_lane_events is the lane's history: each decision (switch, keep),
-- each time it could not act (blocked), its start, pauses and end.

CREATE TABLE IF NOT EXISTS usr.stream_lanes (
    id                 integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer      NOT NULL REFERENCES usr.users(user_id) ON DELETE CASCADE,
    team_id            integer      NOT NULL REFERENCES usr.teams(team_id) ON DELETE CASCADE,
    holder_player_id   integer      NOT NULL,                 -- ESPN player id: who holds the spot now
    holder_name        varchar(120) NOT NULL,
    holder_team        varchar(8),
    original_player_id integer      NOT NULL,                 -- who held it when the lane started
    original_name      varchar(120) NOT NULL,
    start_period       integer      NOT NULL,                 -- the first ESPN day the lane plans for
    end_period         integer      NOT NULL,                 -- the matchup's last ESPN day
    end_date           date         NOT NULL,
    status             varchar(8)   NOT NULL DEFAULT 'active'
                       CHECK (status IN ('active', 'paused', 'ended')),
    notify             varchar(8)   NOT NULL DEFAULT 'email'
                       CHECK (notify IN ('email', 'desk')),   -- desk: no emails
    next_period        integer      NOT NULL,                 -- the ESPN day the next decision is for
    next_decision_at   timestamp with time zone,              -- when it is due, or the claim lease
    attempts           integer      NOT NULL DEFAULT 0,       -- every claim bumps it: the fencing token
    reason             varchar(40),                           -- why it is paused, ended or waiting
    detail             text,
    projection         jsonb,                                 -- the plan as of the last decision
    created_at         timestamp with time zone NOT NULL DEFAULT now(),
    updated_at         timestamp with time zone NOT NULL DEFAULT now(),
    ended_at           timestamp with time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS stream_lanes_one_per_team
    ON usr.stream_lanes (team_id)
    WHERE status IN ('active', 'paused');

CREATE INDEX IF NOT EXISTS stream_lanes_due
    ON usr.stream_lanes (next_decision_at)
    WHERE status = 'active';

CREATE TABLE IF NOT EXISTS usr.stream_lane_events (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lane_id             integer      NOT NULL REFERENCES usr.stream_lanes(id) ON DELETE CASCADE,
    scoring_period_id   integer,                              -- the ESPN day it concerns
    nba_date            date,
    action              varchar(8)   NOT NULL
                        CHECK (action IN ('started', 'switch', 'keep', 'blocked', 'paused', 'resumed', 'ended')),
    add_player_id       integer,                              -- switch: who takes the spot
    add_name            varchar(120),
    drop_player_id      integer,                              -- switch: who leaves it
    drop_name           varchar(120),
    projected_player_id integer,                              -- who the projection before this decision had on the day
    projected_name      varchar(120),
    reason              varchar(40),
    detail              text,
    pickup_id           integer      REFERENCES usr.scheduled_pickups(id) ON DELETE SET NULL,
    created_at          timestamp with time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS stream_lane_events_lane
    ON usr.stream_lane_events (lane_id, id);

ALTER TABLE usr.scheduled_pickups
    ADD COLUMN IF NOT EXISTS lane_id integer REFERENCES usr.stream_lanes(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS scheduled_pickups_lane
    ON usr.scheduled_pickups (lane_id)
    WHERE lane_id IS NOT NULL;
