-- Migration 0041: Dime's memory and the move ledger (the Dime autopilot plan,
-- step 1).
--
-- usr.ai_memory is the agent's notebook: short notes it keeps on a user's teams
-- and leagues between conversations (a plan for the matchup, a thesis about a
-- player with a date to recheck it, an opponent's habit, the user's standing
-- preferences, a lesson from the move ledger). Conversation history stays
-- append-only; this table is the one place the agent may rewrite what it said
-- before. A note is never updated in place: revising one retires it and writes
-- its replacement (`replaces_id`), and forgetting one retires it, so what the
-- agent believed and when stays readable. `team_id` NULL means a note about the
-- user, for every team. `author` says who wrote it: the user's own notes (from
-- the AI desk's "What Dime knows") outrank the agent's, which may not revise or
-- retire them. `conversation_id` is where the agent wrote it.
--
-- usr.move_outcomes is the move ledger: every add and drop a team made, read
-- off the day-to-day differences in usr.lineup_snapshots, and what it earned
-- afterwards, scored from the box scores with the league's own scoring. It is
-- keyed by the provider's ids like the snapshots, so a rival's moves are rows
-- too. `source` says who made a move: Court Vision's own writes are matched
-- through usr.roster_moves (the desk's add/drop is `you`, a scheduled pickup
-- `scheduled`, a stream lane's pickup `lane`, an agent proposal the user sent
-- `dime`); anything else was made outside Court Vision (`outside`): in ESPN
-- itself, on waivers, or by another manager. The ledger is rebuilt whole for a
-- league each night (the backend's /jobs/ledger/run, after data-platform's
-- lineup snapshots), so a row is derived data: `windows` holds each scoring
-- window's totals ({"day", "matchup", "two_weeks"}), and `forecast` / `reason`
-- copy the agent's proposal when there was one, so its expectation sits next
-- to the result.

CREATE TABLE IF NOT EXISTS usr.ai_memory (
    id               bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    team_id          integer      REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    kind             text         NOT NULL,
    text             text         NOT NULL,
    recheck_on       date,
    author           text         NOT NULL,
    conversation_id  bigint       REFERENCES usr.ai_conversations (id) ON DELETE SET NULL,
    replaces_id      bigint       REFERENCES usr.ai_memory (id) ON DELETE SET NULL,
    created_at       timestamp with time zone NOT NULL DEFAULT now(),
    retired_at       timestamp with time zone,
    retired_by       text,
    retired_reason   text,
    CONSTRAINT ai_memory_kind_check
        CHECK (kind IN ('plan', 'player', 'league', 'opponent', 'preference', 'lesson', 'note')),
    CONSTRAINT ai_memory_text_check CHECK (char_length(text) BETWEEN 1 AND 500),
    CONSTRAINT ai_memory_author_check CHECK (author IN ('dime', 'user')),
    CONSTRAINT ai_memory_retired_check
        CHECK ((retired_at IS NULL AND retired_by IS NULL)
               OR (retired_at IS NOT NULL AND retired_by IN ('dime', 'user')))
);

CREATE INDEX IF NOT EXISTS ai_memory_live
    ON usr.ai_memory (user_id, team_id)
    WHERE retired_at IS NULL;

COMMENT ON TABLE usr.ai_memory IS
    'The AI agent''s notes on a user''s teams and leagues, kept between conversations. Revised by '
    'retiring a row and writing its replacement; the user''s own notes (author user) outrank the agent''s.';

CREATE TABLE IF NOT EXISTS usr.move_outcomes (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider           varchar(16)  NOT NULL,
    provider_league_id varchar(64)  NOT NULL,
    season             integer      NOT NULL,
    provider_team_id   integer      NOT NULL,
    team_name          varchar(120) NOT NULL,
    scoring_period_id  integer      NOT NULL,          -- the first day the move counted
    nba_date           date         NOT NULL,          -- that day as a calendar date
    add_player_id      integer,                        -- ESPN
    add_nba_id         integer,
    add_name           varchar(120),
    drop_player_id     integer,                        -- ESPN
    drop_nba_id        integer,
    drop_name          varchar(120),
    paired             boolean      NOT NULL,          -- an add and a drop scored against each other
    source             text         NOT NULL,
    team_id            integer      REFERENCES usr.teams (team_id) ON DELETE SET NULL,
    roster_move_id     integer      REFERENCES usr.roster_moves (id) ON DELETE SET NULL,
    proposal_id        bigint       REFERENCES usr.ai_proposals (id) ON DELETE SET NULL,
    forecast           jsonb,
    reason             text,
    format             text         NOT NULL,
    windows            jsonb        NOT NULL,
    net_points         numeric(8, 2),                  -- the two-week window's add minus drop (points leagues)
    updated_at         timestamp with time zone NOT NULL DEFAULT now(),   -- the rebuild that wrote the row
    CONSTRAINT move_outcomes_provider_check CHECK (provider IN ('espn', 'yahoo')),
    CONSTRAINT move_outcomes_source_check
        CHECK (source IN ('you', 'scheduled', 'lane', 'dime', 'outside')),
    CONSTRAINT move_outcomes_format_check CHECK (format IN ('points', 'categories')),
    CONSTRAINT move_outcomes_player_check CHECK (add_player_id IS NOT NULL OR drop_player_id IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS move_outcomes_move_uq
    ON usr.move_outcomes (provider, provider_league_id, season, provider_team_id, scoring_period_id,
                          COALESCE(add_player_id, 0), COALESCE(drop_player_id, 0));

CREATE INDEX IF NOT EXISTS move_outcomes_team
    ON usr.move_outcomes (team_id, nba_date DESC)
    WHERE team_id IS NOT NULL;

COMMENT ON TABLE usr.move_outcomes IS
    'The move ledger: each add/drop read off usr.lineup_snapshots and what it earned in the box scores, '
    'scored with the league''s scoring. Rebuilt per league nightly by the backend; derived data.';
