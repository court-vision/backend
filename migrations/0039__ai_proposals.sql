-- Migration 0039: the AI agent's proposals (the CV AI plan, § 6: step 5, chips).
--
-- usr.ai_proposals is one roster move the agent proposed with `propose_move`,
-- checked by the server before it was stored and shown to the user as a chip in
-- the AI desk. The chip is staged into the Week desk's tray (rendered in the AI
-- desk) and sent by its slider through the same routes as any other move: the
-- roster transaction (`kind = 'transaction'`, a move for today) or the scheduled
-- pickup (`kind = 'scheduled'`, a move for a later matchup day). The send
-- carries the proposal's id, and the route marks it `sent` with the write's
-- audit id or the pickup's id. Nothing is ever executed from the AI desk itself.
--
-- `state`: proposed (the chip can be staged), sent, dismissed (the user let it
-- go). "Expired" is read off `expires_at` (a move today: the day's first tip-off,
-- or the rollover into the next day; a scheduled move: the rollover into its day,
-- when scheduling for it closes), never stored. A refused send leaves the row
-- proposed, for a retry from the tray; a send always wins over a dismiss that
-- raced it, since the move was made. Player ids are ESPN's (what the writes
-- take) with the NBA id beside each; `day` is the matchup day index the tools
-- count (0 = the matchup's first day). `turn_id` is filled when the turn that
-- made the proposal is written.

CREATE TABLE IF NOT EXISTS usr.ai_proposals (
    id                 bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            integer  NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    conversation_id    bigint   NOT NULL REFERENCES usr.ai_conversations (id) ON DELETE CASCADE,
    turn_id            bigint   REFERENCES usr.ai_turns (id) ON DELETE SET NULL,
    team_id            integer  NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    kind               text     NOT NULL,
    day                integer  NOT NULL,
    scoring_period_id  integer  NOT NULL,
    nba_date           date     NOT NULL,
    add_player_id      integer,
    add_nba_id         integer,
    add_name           text,
    add_team           text,
    drop_player_id     integer,
    drop_nba_id        integer,
    drop_name          text,
    drop_team          text,
    reason             text     NOT NULL,
    summary            text     NOT NULL,
    projection         jsonb,
    state              text     NOT NULL DEFAULT 'proposed',
    expires_at         timestamp with time zone NOT NULL,
    created_at         timestamp with time zone NOT NULL DEFAULT now(),
    updated_at         timestamp with time zone NOT NULL DEFAULT now(),
    sent_at            timestamp with time zone,
    audit_id           integer,
    pickup_id          integer,
    CONSTRAINT ai_proposals_kind_check CHECK (kind IN ('transaction', 'scheduled')),
    CONSTRAINT ai_proposals_state_check CHECK (state IN ('proposed', 'sent', 'dismissed')),
    CONSTRAINT ai_proposals_move_check CHECK (add_player_id IS NOT NULL OR drop_player_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS ai_proposals_conversation_idx
    ON usr.ai_proposals (conversation_id, id);

COMMENT ON TABLE usr.ai_proposals IS
  'Roster moves the AI agent proposed (chips in the AI desk). Sent through the Week desk''s routes, which mark them sent; never executed from the desk.';
