-- Migration 0050: nba.daily_rankings, a ranking stored every morning (the Live
-- rankings plan, step 1).
--
-- Court Vision's rankings were only ever computed on read, so nothing could say
-- how a player's rank moved, when ESPN last changed its own, or which of the two
-- was right. This table keeps both, one row per player per board per source per
-- day:
--
--   source  'cv'   Court Vision's board as the Draft lab shows it to a room with
--                  no league: the standard league (twelve teams, thirteen
--                  rounds, ESPN's default playoff weeks), priced on the games
--                  still to come. `model` names what built it, so a later model
--                  is a new value here and never a silent change of meaning.
--           'espn' ESPN's own rank that morning, read from the same public
--                  league the preseason market snapshot reads. Its in-season
--                  ranks move only when its writers update them; storing every
--                  day's shows when that was.
--           Any other value is a candidate Court Vision board graded beside
--           'cv' before it replaces it (the analyst's board, in shadow).
--   board   'points' (ESPN's default points weights; ESPN's STANDARD rank) or
--           'categories' (the standard nine categories; ESPN's ROTO rank).
--
-- as_of_date is the fantasy day the board was built for: its games count from
-- that day on. One board a day; a rerun replaces the day's rows.
--
-- value / score / games are the board's own numbers and mean what the source
-- means by them. For 'cv': `value` is the per-game number the board shows
-- (fantasy points per game, or the nine-category index), `score` is what the
-- rank is ordered by (fantasy points over the games left, or the summed
-- category score), `games` is the games he is expected to play from here. For
-- 'espn': `value` is its auction value and the other two are null.
--
-- Written by data-platform's daily_rankings pipeline (the backend builds the
-- 'cv' boards and hands them over; it keeps no second copy of the write), read
-- by the backend. No rows are ever pruned: the history is the point.

SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS nba.daily_rankings (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of_date      date         NOT NULL,
    season          varchar(7)   NOT NULL,      -- e.g. '2026-27'
    source          varchar(16)  NOT NULL,      -- cv | espn | a candidate board's name
    board           varchar(12)  NOT NULL CHECK (board IN ('points', 'categories')),
    player_id       integer      NOT NULL REFERENCES nba.players(id) ON DELETE CASCADE,
    rank            integer      NOT NULL CHECK (rank >= 1),
    value           numeric(8, 2),
    score           numeric(10, 3),
    games           numeric(6, 2),
    season_gp       smallint,                   -- games he had played this season that morning
    injury_status   varchar(20),                -- the source's own flag that morning; null is healthy
    line_source     varchar(12),                -- cv: projection | season | baseline, where his line came from
    model           varchar(32),                -- cv: what built the board
    pipeline_run_id uuid,
    created_at      timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT daily_rankings_day_uq UNIQUE (as_of_date, source, board, player_id)
);

-- One player's history on one board, newest first: his moves, and the day
-- ESPN's rank last changed.
CREATE INDEX IF NOT EXISTS daily_rankings_player
    ON nba.daily_rankings (player_id, source, board, as_of_date DESC);
