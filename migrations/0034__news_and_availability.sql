-- Migration 0034: news items and player availability (docs/NEWS_AND_INJURY_PIPELINES_PLAN.md § 1).
--
-- Four nba.* tables, written by data-platform and read by the backend:
--
--   nba.news_items            one row per item from any source (ESPN injuries
--                             notes, ESPN per-player news, RSS feeds, ...),
--                             unique on (source, source_item_id). `content_hash`
--                             is the normalized headline, for cross-source dedup
--                             (ESPN's injury notes and its per-player Rotowire
--                             items are the same text). `raw` is pruned after
--                             30 days; `search` is generated for full-text reads.
--   nba.news_item_players /   which players and teams an item is about, and how
--   nba.news_item_teams       the player was linked (an ESPN id or a name match).
--   nba.availability_reports  append-only observations: one row per (source,
--                             player, game or date) status *change*. The pipeline
--                             inserts only when (status, reason) differs from that
--                             source's latest row for the player and date, so a
--                             2-minute poll that sees nothing new writes nothing.
--   nba.player_availability   the resolved verdict, one row per (player, game
--                             date). `changed_at` moves only when `verdict`
--                             changes; it is what the late-scratch reactor keys
--                             on. `previous_verdict` drives the "upgraded
--                             doubtful" planner rule.
--
-- game_id carries no foreign key: the pipeline reads it from the source (the NBA
-- report, the box score) and a game row can arrive after the first report about
-- it. player_id references nba.players like every other stat table.
--
-- usr.roster_moves gains a fourth source, 'availability' (a reaction to a verdict
-- change), and `trigger_player_id`, the NBA id of the player whose verdict caused
-- it. `source` was varchar(10), one short of 'availability', so it widens to 16.
-- The partial unique index makes "one counted reaction per scratch per team per
-- day" a database fact and leaves the auto-lineup once-per-day index alone. 0028
-- is the precedent for the CHECK swap.

SET LOCAL lock_timeout = '5s';

CREATE TABLE IF NOT EXISTS nba.news_items (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          varchar(24)  NOT NULL,      -- espn_injuries | espn_player_news | espn_site_news | rotowire_rss | realgm_rss | ...
    source_item_id  varchar(200) NOT NULL,      -- the source's own id, or a hash of url + headline
    published_at    timestamp with time zone,   -- the source's timestamp
    fetched_at      timestamp with time zone NOT NULL DEFAULT now(),
    headline        text         NOT NULL,
    body            text,                       -- the blurb / one paragraph, never a full article
    url             text,
    attribution     text,                       -- "per Shams Charania of ESPN", the feed's author
    kind            varchar(16)  NOT NULL DEFAULT 'other'
                    CHECK (kind IN ('injury', 'availability', 'lineup', 'transaction', 'performance', 'rumor', 'other')),
    content_hash    varchar(64),
    raw             jsonb,
    search          tsvector GENERATED ALWAYS AS
                    (to_tsvector('english', coalesce(headline, '') || ' ' || coalesce(body, ''))) STORED,
    CONSTRAINT news_items_source_item_uq UNIQUE (source, source_item_id)
);

CREATE INDEX IF NOT EXISTS news_items_published ON nba.news_items (published_at DESC);
CREATE INDEX IF NOT EXISTS news_items_kind_published ON nba.news_items (kind, published_at DESC);
CREATE INDEX IF NOT EXISTS news_items_content_hash ON nba.news_items (content_hash);
CREATE INDEX IF NOT EXISTS news_items_search ON nba.news_items USING gin (search);

CREATE TABLE IF NOT EXISTS nba.news_item_players (
    news_item_id    bigint      NOT NULL REFERENCES nba.news_items(id) ON DELETE CASCADE,
    player_id       integer     NOT NULL REFERENCES nba.players(id) ON DELETE CASCADE,
    linked_by       varchar(8)  NOT NULL CHECK (linked_by IN ('espn_id', 'name')),
    PRIMARY KEY (news_item_id, player_id)
);

CREATE INDEX IF NOT EXISTS news_item_players_player ON nba.news_item_players (player_id);

CREATE TABLE IF NOT EXISTS nba.news_item_teams (
    news_item_id    bigint      NOT NULL REFERENCES nba.news_items(id) ON DELETE CASCADE,
    team_id         varchar(3)  NOT NULL REFERENCES nba.teams(id) ON DELETE CASCADE,
    PRIMARY KEY (news_item_id, team_id)
);

CREATE INDEX IF NOT EXISTS news_item_teams_team ON nba.news_item_teams (team_id);

CREATE TABLE IF NOT EXISTS nba.availability_reports (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id       integer      NOT NULL REFERENCES nba.players(id) ON DELETE CASCADE,
    game_id         varchar(20),                -- when the source is per game (NBA report, box score)
    game_date       date         NOT NULL,      -- the game's NBA date, or the report date for roster-level sources
    source          varchar(16)  NOT NULL
                    CHECK (source IN ('nba_boxscore', 'nba_report', 'espn_injuries', 'espn_fantasy', 'news_claim')),
    status          varchar(12)  NOT NULL
                    CHECK (status IN ('out', 'doubtful', 'questionable', 'probable', 'available', 'inactive', 'active')),
    reason          varchar(100),               -- body part / Rest / Illness / Personal / Suspension / G League
    detail          text,                       -- the source's wording
    expected_return date,
    source_time     timestamp with time zone,   -- the source's own timestamp (ESPN `date`, report filename time)
    observed_at     timestamp with time zone NOT NULL DEFAULT now(),
    confidence      smallint     NOT NULL CHECK (confidence BETWEEN 0 AND 100),
    news_item_id    bigint       REFERENCES nba.news_items(id) ON DELETE SET NULL,
    pipeline_run_id uuid
);

-- "That source's latest row for the player and date", the idempotency read.
CREATE INDEX IF NOT EXISTS availability_reports_latest
    ON nba.availability_reports (player_id, game_date, source, observed_at DESC);
CREATE INDEX IF NOT EXISTS availability_reports_observed ON nba.availability_reports (observed_at);

CREATE TABLE IF NOT EXISTS nba.player_availability (
    player_id        integer      NOT NULL REFERENCES nba.players(id) ON DELETE CASCADE,
    game_date        date         NOT NULL,
    game_id          varchar(20),
    verdict          varchar(12)  NOT NULL
                     CHECK (verdict IN ('out', 'doubtful', 'questionable', 'probable', 'available', 'unknown')),
    final            boolean      NOT NULL DEFAULT false,   -- the box score has spoken
    decided_by       varchar(16),                           -- the source that won
    reason           varchar(100),
    detail           text,
    expected_return  date,
    confidence       smallint,
    previous_verdict varchar(12)
                     CHECK (previous_verdict IN ('out', 'doubtful', 'questionable', 'probable', 'available', 'unknown')),
    changed_at       timestamp with time zone NOT NULL DEFAULT now(),
    updated_at       timestamp with time zone NOT NULL DEFAULT now(),
    PRIMARY KEY (player_id, game_date)
);

CREATE INDEX IF NOT EXISTS player_availability_date_changed
    ON nba.player_availability (game_date, changed_at);

ALTER TABLE usr.roster_moves ALTER COLUMN source TYPE varchar(16);

ALTER TABLE usr.roster_moves ADD COLUMN IF NOT EXISTS trigger_player_id integer;

ALTER TABLE usr.roster_moves
    DROP CONSTRAINT IF EXISTS roster_moves_source_check;

ALTER TABLE usr.roster_moves
    ADD CONSTRAINT roster_moves_source_check
    CHECK (source IN ('manual', 'auto', 'scheduled', 'availability'));

CREATE UNIQUE INDEX IF NOT EXISTS roster_moves_availability_once_uq
    ON usr.roster_moves (team_id, nba_date, trigger_player_id)
    WHERE source = 'availability' AND status IN ('applied', 'applied_unverified', 'noop');
