-- Migration 0048: protected players (the roster lock; the "Roster lock" initiative doc).
--
-- A protected player can't leave the roster through Court Vision: nothing drops him
-- (the Week desk's add/drop and drop alone, a scheduled pickup, a stream lane, Dime's
-- chips and autopilot) and nothing suggests dropping him (the market's Make room list,
-- the daily streamer swap, Dime's what-ifs and stream plans) until the user unprotects
-- him. Every add/drop Court Vision sends passes the roster transaction's write chain,
-- which refuses a protected drop; the earlier checks only give the reason sooner.
-- Lineup (slot) moves are untouched: auto-lineup and late-scratch swaps still move him.
--
-- One row per protected player per team; unprotecting deletes the row. Only the user
-- sets or clears one (Dime can't), and protecting cancels what would drop him: the
-- pending pickups that drop him, and the stream lanes holding his spot.

CREATE TABLE IF NOT EXISTS usr.roster_protections (
    id             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id        integer      NOT NULL REFERENCES usr.teams (team_id) ON DELETE CASCADE,
    user_id        integer      NOT NULL REFERENCES usr.users (user_id) ON DELETE CASCADE,
    player_id      integer      NOT NULL,              -- ESPN, as the boards and the pool key players
    nba_player_id  integer,
    player_name    text         NOT NULL,
    player_team    text,
    created_at     timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT roster_protections_team_player_key UNIQUE (team_id, player_id)
);

COMMENT ON TABLE usr.roster_protections IS
    'Players the user protected on a team: Court Vision never drops one or suggests dropping one until the '
    'user unprotects him. Set and cleared from the Week desk; Dime reads them and works around them.';
